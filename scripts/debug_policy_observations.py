def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Export the minimal observation/action contract needed to validate "
            "a Kinova policy implementation on a real robot."
        )
    )
    parser.add_argument(
        "training_set",
        help="Path to the training-set YAML used to resolve the run parameters.",
    )
    parser.add_argument(
        "--run",
        required=True,
        dest="run_name",
        help="Run name inside the training set (for example all_randomization_no_joint_pos).",
    )
    parser.add_argument(
        "--checkpoint-file",
        required=True,
        help="Path to the local .pt checkpoint file to inspect.",
    )
    parser.add_argument(
        "--steps",
        type=int,
        default=1,
        help="Number of environment steps to print. Default: 1.",
    )
    parser.add_argument(
        "--device",
        default=None,
        help="Torch device to use. Default: cuda:0 if available, else cpu.",
    )
    parser.add_argument(
        "--json-out",
        default=None,
        help="Optional path to dump the collected debug data as JSON.",
    )
    parser.add_argument(
        "--real-obs-json",
        default=None,
        help=(
            "Optional JSON file containing real-robot actor observations to compare against the checkpoint. "
            "Accepted formats: raw actor_obs vector, actor_terms mapping, or a full dump generated by this script."
        ),
    )
    parser.add_argument(
        "--real-obs-step",
        type=int,
        default=0,
        help="Step index to read when --real-obs-json points to a multi-record dump. Default: 0.",
    )
    parser.add_argument(
        "--precision",
        type=int,
        default=6,
        help="Number of decimals to print. Default: 6.",
    )
    return parser.parse_args()


def _resolve_run_params(training_set_path: Path, run_name: str):
    training_set_cfg = _load_training_set(training_set_path)
    base_params = _base_parameters(training_set_cfg, training_set_path=training_set_path)

    matched: tuple[str, list[str], dict[str, Any]] | None = None
    for index, raw_run_cfg in enumerate(training_set_cfg["runs"]):
        raw_run_cfg = _resolve_run_cfg(
            raw_run_cfg,
            index=index,
            relative_to=training_set_path.parent,
        )
        candidate_name, preset_refs, overrides = _normalize_run(raw_run_cfg, index=index)
        if candidate_name == run_name:
            variant = _resolve_run_variant(
                training_set_cfg,
                raw_run_cfg,
                run_name=candidate_name,
            )
            matched = (variant, preset_refs, overrides)
            break

    if matched is None:
        raise ValueError(f"Run `{run_name}` was not found in {training_set_path}")

    variant, preset_refs, overrides = matched
    params = _build_run_parameters(
        run_name=run_name,
        preset_refs=preset_refs,
        overrides=overrides,
        training_set_path=training_set_path,
        base_params=base_params,
    )
    return variant, params


def _actor_term_debug_payload(env: ManagerBasedRlEnv) -> list[dict[str, Any]]:
    manager = env.observation_manager
    actor_terms = manager.active_terms["actor"]
    actor_dims = manager._group_obs_term_dim["actor"]
    actor_cfgs = manager._group_obs_term_cfgs["actor"]
    obs_entries = dict(manager.get_active_iterable_terms(0))

    payload: list[dict[str, Any]] = []
    offset = 0
    for name, dims, cfg in zip(actor_terms, actor_dims, actor_cfgs, strict=False):
        key = f"actor-{name}"
        flat = torch.tensor(obs_entries[key], dtype=torch.float32)
        size = int(math.prod(dims))
        entry: dict[str, Any] = {
            "name": name,
            "flat_shape": list(dims),
            "offset_start": offset,
            "offset_end": offset + size,
            "flat": flat.tolist(),
        }
        if cfg.history_length > 0 and cfg.flatten_history_dim:
            per_timestep_dim = int(flat.numel() // cfg.history_length)
            history = flat.view(cfg.history_length, per_timestep_dim)
            entry["history_length"] = int(cfg.history_length)
            entry["history_order"] = "oldest_to_newest"
            entry["history"] = history.tolist()
            entry["current"] = history[-1].tolist()
        else:
            entry["current"] = flat.tolist()
        payload.append(entry)
        offset += size
    return payload


def _actor_layout(term_payload: list[dict[str, Any]]) -> list[dict[str, Any]]:
    return [
        {
            key: entry[key]
            for key in (
                "name",
                "flat_shape",
                "offset_start",
                "offset_end",
                "history_length",
                "history_order",
            )
            if key in entry
        }
        for entry in term_payload
    ]


def _actor_term_semantics(
    variant: str, ee_ft_wrench_mode: str = "raw"
) -> dict[str, str]:
    if ee_ft_wrench_mode == "weight_compensated":
        ee_ft_semantics = (
            "F/T sensor frame, force xyz then torque xyz, static racquet-side "
            "weight removed"
        )
    elif ee_ft_wrench_mode == "mc_rtc_calibrated":
        ee_ft_semantics = (
            "actual (calibrated) F/T sensor frame, force xyz then torque xyz, "
            "calibrated payload weight removed; matches mc_rtc wrenchWithoutGravity"
        )
    else:
        ee_ft_semantics = "F/T sensor frame, force xyz then torque xyz, raw sensor values"

    shared = {
        "ee_vel": "racquet_frame origin linear velocity, world frame, xyz",
        "ee_ang_vel": "racquet_frame angular velocity, world frame, xyz",
        "ee_ft_wrench": ee_ft_semantics,
        "actions": "last raw action submitted to the environment; unbounded unless wrapper_clip_actions is set",
    }
    if variant == "joint":
        return {
            "joint_pos": "joint position minus default joint position q0, joint_1 through joint_7",
            "joint_vel": "joint velocity minus default joint velocity, joint_1 through joint_7",
            "ee_pos": "racquet_frame origin position, world frame, xyz",
            "ee_quat": "racquet_frame orientation in world, quaternion wxyz reconstructed from rotation matrix",
            **shared,
        }
    return {
        "ee_pos": "racquet_frame origin position relative to nominal reset pose p - p0, xyz",
        "ee_quat": "racquet_frame orientation relative to nominal reset orientation, positive-w quaternion wxyz",
        **shared,
    }


def _robot_command_mapping(
    env: ManagerBasedRlEnv,
    policy_action: torch.Tensor,
    clip_actions: float | None,
) -> dict[str, Any]:
    action_sent = (
        torch.clamp(policy_action, -clip_actions, clip_actions)
        if clip_actions is not None
        else policy_action
    )
    action_name = env.action_manager.active_terms[0]
    action_term = env.action_manager.get_term(action_name)
    payload: dict[str, Any] = {
        "wrapper_clip_actions": clip_actions,
        "policy_output": policy_action[0].detach().cpu().tolist(),
        "action_sent_to_env": action_sent[0].detach().cpu().tolist(),
    }

    if action_name == "joint_pos":
        scale = action_term.scale
        offset = action_term.offset
        scale_tensor = scale if isinstance(scale, torch.Tensor) else torch.tensor(scale)
        offset_tensor = offset if isinstance(offset, torch.Tensor) else torch.tensor(offset)
        if scale_tensor.ndim > 1:
            scale_tensor = scale_tensor[0]
        if offset_tensor.ndim > 1:
            offset_tensor = offset_tensor[0]
        joint_target = offset_tensor.to(action_sent.device) + scale_tensor.to(
            action_sent.device
        ) * action_sent[0]
        payload["semantics"] = "q_ref = action_offset + action_scale * clipped_policy_output"
        payload["action_scale"] = scale_tensor.detach().cpu().tolist()
        payload["action_offset"] = offset_tensor.detach().cpu().tolist()
        payload["joint_position_target"] = joint_target.detach().cpu().tolist()
    else:
        cfg = action_term.cfg
        payload["semantics"] = (
            "p_ref = p_0 + delta_pos_scale * action[:3]; "
            "R_ref = R_0 * Exp(delta_ori_scale * action[3:6])"
        )
        payload["delta_pos_scale"] = cfg.delta_pos_scale
        payload["delta_ori_scale"] = cfg.delta_ori_scale
    return payload


def _deployment_inputs(
    variant: str,
    env: ManagerBasedRlEnv,
    term_payload: list[dict[str, Any]],
    calib_file: str | None = None,
) -> dict[str, Any]:
    """Return the current physical quantities needed to rebuild actor observations."""
    robot = env.scene["robot"]
    force_sensor = env.scene["robot/EEForceSensor_fsensor"]
    torque_sensor = env.scene["robot/EEForceSensor_tsensor"]
    raw_wrench = torch.cat((force_sensor.data, torque_sensor.data), dim=-1)
    weight_effect = bb_mdp.ee_ft_racquet_weight_effect(env)
    actor_current = {entry["name"]: entry["current"] for entry in term_payload}

    payload: dict[str, Any] = {
        "joint_names": list(robot.joint_names),
        "joint_pos": robot.data.joint_pos[0].detach().cpu().tolist(),
        "default_joint_pos": robot.data.default_joint_pos[0].detach().cpu().tolist(),
        "joint_vel": robot.data.joint_vel[0].detach().cpu().tolist(),
        "default_joint_vel": robot.data.default_joint_vel[0].detach().cpu().tolist(),
        "racquet_frame_lin_vel_w": actor_current["ee_vel"],
        "racquet_frame_ang_vel_w": actor_current["ee_ang_vel"],
        "ee_ft_raw_wrench_force_torque": raw_wrench[0].detach().cpu().tolist(),
        "ee_ft_racquet_weight_effect": weight_effect[0].detach().cpu().tolist(),
        "ee_ft_corrected_wrench_force_torque": (
            raw_wrench[0] - weight_effect[0]
        ).detach().cpu().tolist(),
        "last_raw_policy_action": actor_current["actions"],
    }
    if calib_file is not None:
        # Exported alongside the other two so the mc_rtc-frame signal can be compared
        # directly against a real-robot capture.
        payload["ee_ft_mc_rtc_calibrated_wrench_force_torque"] = (
            bb_mdp.ee_ft_mc_rtc_calibrated_wrench(env, calib_file, wrench=raw_wrench)[0]
            .detach()
            .cpu()
            .tolist()
        )
    if variant == "joint":
        payload["racquet_frame_pos_w"] = actor_current["ee_pos"]
        payload["racquet_frame_quat_w_wxyz"] = actor_current["ee_quat"]
        payload["joint_pos_rel"] = (
            robot.data.joint_pos[0] - robot.data.default_joint_pos[0]
        ).detach().cpu().tolist()
        payload["joint_vel_rel"] = (
            robot.data.joint_vel[0] - robot.data.default_joint_vel[0]
        ).detach().cpu().tolist()
    else:
        payload["racquet_frame_pos_rel_nominal"] = actor_current["ee_pos"]
        payload["racquet_frame_quat_rel_nominal_wxyz"] = actor_current["ee_quat"]
    return payload


def _print_mapping(name: str, payload: dict[str, Any]) -> None:
    print(f"=== {name} ===")
    for name, values in payload.items():
        if isinstance(values, str) or name == "joint_names" or values is None:
            print(f"{name}: {values}")
        else:
            print(f"{name}: {torch.tensor(values)}")
    print()


def _print_term_current_values(term_payload: list[dict[str, Any]]) -> None:
    print("=== current actor terms ===")
    for entry in term_payload:
        name = entry["name"]
        print(
            f"actor/{name} offset=[{entry['offset_start']}:{entry['offset_end']}] "
            f"current={torch.tensor(entry['current'])}"
        )
    print()


def _flatten_real_term_payload(term_payload: list[dict[str, Any]], actor_term_order: list[str]) -> list[float]:
    terms_by_name = {entry["name"]: entry for entry in term_payload}
    flattened: list[float] = []
    for name in actor_term_order:
        if name not in terms_by_name:
            raise KeyError(f"Missing actor term `{name}` in real observation payload")
        flattened.extend(terms_by_name[name]["flat"])
    return flattened


def _flatten_term_mapping(term_mapping: dict[str, Any], actor_term_order: list[str]) -> list[float]:
    flattened: list[float] = []
    for name in actor_term_order:
        if name not in term_mapping:
            raise KeyError(f"Missing actor term `{name}` in real observation mapping")
        value = term_mapping[name]
        tensor = torch.tensor(value, dtype=torch.float32)
        flattened.extend(tensor.reshape(-1).tolist())
    return flattened


def _load_real_actor_obs(json_path: Path, actor_term_order: list[str], step: int) -> torch.Tensor:
    payload = json.loads(json_path.read_text(encoding="utf-8"))

    if isinstance(payload, dict) and "records" in payload:
        records = payload["records"]
        if not isinstance(records, list) or not records:
            raise ValueError(f"`records` in {json_path} must be a non-empty list")
        if step < 0 or step >= len(records):
            raise IndexError(f"Requested real observation step {step} but only {len(records)} records are available")
        record = records[step]
        if "actor_obs" in record:
            return torch.tensor(record["actor_obs"], dtype=torch.float32).unsqueeze(0)
        if "actor_terms" in record:
            flat = _flatten_real_term_payload(record["actor_terms"], actor_term_order)
            return torch.tensor(flat, dtype=torch.float32).unsqueeze(0)
        raise ValueError(f"Record {step} in {json_path} does not contain `actor_obs` or `actor_terms`")

    if isinstance(payload, dict) and "actor_obs" in payload:
        return torch.tensor(payload["actor_obs"], dtype=torch.float32).unsqueeze(0)

    if isinstance(payload, dict) and "actor_terms" in payload:
        actor_terms = payload["actor_terms"]
        if isinstance(actor_terms, list):
            flat = _flatten_real_term_payload(actor_terms, actor_term_order)
        elif isinstance(actor_terms, dict):
            flat = _flatten_term_mapping(actor_terms, actor_term_order)
        else:
            raise TypeError("`actor_terms` must be a list or mapping")
        return torch.tensor(flat, dtype=torch.float32).unsqueeze(0)

    if isinstance(payload, dict) and all(name in payload for name in actor_term_order):
        flat = _flatten_term_mapping(payload, actor_term_order)
        return torch.tensor(flat, dtype=torch.float32).unsqueeze(0)

    if isinstance(payload, list):
        return torch.tensor(payload, dtype=torch.float32).unsqueeze(0)

    raise ValueError(
        f"Unsupported real observation JSON format in {json_path}. "
        "Expected a raw vector, actor_terms mapping, or a dump generated by this script."
    )


def _compare_and_print_real_obs(
    *,
    real_actor_obs: torch.Tensor,
    sim_actor_obs: torch.Tensor,
    sim_normalized_actor_obs: torch.Tensor,
    sim_action: torch.Tensor,
    policy,
) -> dict[str, Any]:
    with torch.no_grad():
        if hasattr(policy, "obs_normalizer"):
            real_actor_obs_normalized = policy.obs_normalizer(real_actor_obs.clone())
        else:
            real_actor_obs_normalized = real_actor_obs.clone()
        real_action = policy({"actor": real_actor_obs})

    actor_obs_abs_diff = torch.abs(real_actor_obs - sim_actor_obs)
    normalized_abs_diff = torch.abs(real_actor_obs_normalized - sim_normalized_actor_obs)
    action_abs_diff = torch.abs(real_action - sim_action)

    print("=== real-vs-sim comparison ===")
    print(f"real_actor_obs shape={tuple(real_actor_obs.shape)}")
    print(real_actor_obs[0])
    print()
    print(f"real_actor_obs_normalized shape={tuple(real_actor_obs_normalized.shape)}")
    print(real_actor_obs_normalized[0])
    print()
    print(f"real_policy_action shape={tuple(real_action.shape)}")
    print(real_action[0])
    print()
    print("abs_diff(actor_obs)")
    print(actor_obs_abs_diff[0])
    print()
    print("abs_diff(actor_obs_normalized)")
    print(normalized_abs_diff[0])
    print()
    print("abs_diff(policy_action)")
    print(action_abs_diff[0])
    print()

    return {
        "real_actor_obs": real_actor_obs[0].cpu().tolist(),
        "real_actor_obs_normalized": real_actor_obs_normalized[0].cpu().tolist(),
        "real_policy_action": real_action[0].cpu().tolist(),
        "abs_diff_actor_obs": actor_obs_abs_diff[0].cpu().tolist(),
        "abs_diff_actor_obs_normalized": normalized_abs_diff[0].cpu().tolist(),
        "abs_diff_policy_action": action_abs_diff[0].cpu().tolist(),
        "max_abs_diff_actor_obs": float(actor_obs_abs_diff.max().item()),
        "max_abs_diff_actor_obs_normalized": float(normalized_abs_diff.max().item()),
        "max_abs_diff_policy_action": float(action_abs_diff.max().item()),
    }

def main() -> int:
    args = _parse_args()
    torch.set_printoptions(precision=args.precision, sci_mode=False, linewidth=160)

    training_set_path = Path(args.training_set).resolve()
    checkpoint_path = Path(args.checkpoint_file).resolve()
    if not checkpoint_path.exists():
        raise FileNotFoundError(f"Checkpoint file not found: {checkpoint_path}")

    variant, params = _resolve_run_params(training_set_path, args.run_name)
    task_id = TASK_ID_BY_VARIANT[variant]
    device = args.device or ("cuda:0" if torch.cuda.is_available() else "cpu")

    print(f"[obs-debug] task_id={task_id}")
    print(f"[obs-debug] variant={variant}")
    print(f"[obs-debug] run={args.run_name}")
    print(f"[obs-debug] checkpoint={checkpoint_path}")
    print(f"[obs-debug] device={device}")
    print(f"[obs-debug] note: ee_quat uses wxyz order")

    env_cfg = kinova_ball_balancing_env_cfg(variant=variant, play=True, params=params)
    env_cfg.scene.num_envs = 1
    env = ManagerBasedRlEnv(cfg=env_cfg, device=device, render_mode=None)
    runner_cfg = kinova_ppo_runner_cfg(variant=variant, params=params)
    vec_env = RslRlVecEnvWrapper(env, clip_actions=runner_cfg.clip_actions)
    print(f"[obs-debug] wrapper clip_actions={runner_cfg.clip_actions}")
    print(
        "[obs-debug] actor observation corruption="
        f"{env.observation_manager.cfg['actor'].enable_corruption} (play mode)"
    )
    print("[obs-debug] ONNX output is the raw deterministic policy output")

    try:
        runner_cls = load_runner_cls(task_id) or MjlabOnPolicyRunner
        runner = runner_cls(vec_env, asdict(runner_cfg), device=device)
        runner.load(str(checkpoint_path), load_cfg={"actor": True}, strict=True, map_location=device)
        policy = runner.get_inference_policy(device=device)

        obs_td, _ = vec_env.reset()
        records: list[dict[str, Any]] = []

        actor_term_order = env.observation_manager.active_terms["actor"]

        for step_idx in range(args.steps):
            actor_obs = obs_td["actor"].detach().clone()
            with torch.no_grad():
                if hasattr(policy, "obs_normalizer"):
                    normalized_actor_obs = policy.obs_normalizer(actor_obs.clone())
                else:
                    normalized_actor_obs = actor_obs.clone()
                action = policy(obs_td)

            term_payload = _actor_term_debug_payload(env)
            robot_command_mapping = _robot_command_mapping(
                env, action, runner_cfg.clip_actions
            )
            deployment_inputs = _deployment_inputs(
                variant,
                env,
                term_payload,
                calib_file=str(params.resolved_ee_ft_calib_file()),
            )

            print(f"\n=== step {step_idx} ===")
            print(f"actor_obs shape={tuple(actor_obs.shape)}")
            print(actor_obs[0])
            print()
            print(f"actor_obs_normalized shape={tuple(normalized_actor_obs.shape)}")
            print(normalized_actor_obs[0])
            print()
            print(f"policy_action shape={tuple(action.shape)}")
            print(action[0])
            print()
            _print_mapping("robot command mapping", robot_command_mapping)
            _print_mapping("deployment inputs", deployment_inputs)
            _print_term_current_values(term_payload)

            real_comparison = None
            if args.real_obs_json is not None:
                real_actor_obs = _load_real_actor_obs(
                    Path(args.real_obs_json).resolve(),
                    actor_term_order=actor_term_order,
                    step=args.real_obs_step + step_idx,
                ).to(actor_obs.device)
                real_comparison = _compare_and_print_real_obs(
                    real_actor_obs=real_actor_obs,
                    sim_actor_obs=actor_obs,
                    sim_normalized_actor_obs=normalized_actor_obs,
                    sim_action=action,
                    policy=policy,
                )

            records.append(
                {
                    "step": step_idx,
                    "actor_obs": actor_obs[0].cpu().tolist(),
                    "actor_obs_normalized": normalized_actor_obs[0].cpu().tolist(),
                    "policy_action": action[0].cpu().tolist(),
                    "robot_command_mapping": robot_command_mapping,
                    "deployment_inputs": deployment_inputs,
                    "actor_terms": term_payload,
                    "real_comparison": real_comparison,
                }
            )

            if step_idx + 1 < args.steps:
                obs_td, _, _, _ = vec_env.step(action)

        if args.json_out is not None:
            policy_dt_s = (
                float(params.simulation.timestep) * float(params.simulation.decimation)
            )
            payload = {
                "task_id": task_id,
                "variant": variant,
                "run_name": args.run_name,
                "checkpoint_file": str(checkpoint_path),
                "device": device,
                "policy_dt_s": policy_dt_s,
                "wrapper_clip_actions": runner_cfg.clip_actions,
                "actor_observation_corruption": env.observation_manager.cfg[
                    "actor"
                ].enable_corruption,
                "onnx_output_semantics": "raw_deterministic_policy_output",
                "implementation_contract": {
                    "build_actor_obs": (
                        "Concatenate actor terms in actor_term_order. Each term history "
                        "is flattened oldest_to_newest."
                    ),
                    "policy_input": (
                        "Use actor_obs directly when running exported ONNX. "
                        "actor_obs_normalized is included only to debug checkpoint-side "
                        "normalization."
                    ),
                    "policy_output": (
                        "Deterministic raw action. Apply wrapper_clip_actions before "
                        "mapping it to the robot command."
                    ),
                },
                "actor_term_order": actor_term_order,
                "actor_term_semantics": _actor_term_semantics(
                    variant,
                    ee_ft_wrench_mode=params.ee_ft_wrench_mode,
                ),
                "actor_layout": _actor_layout(records[0]["actor_terms"]),
                "history_order": "oldest_to_newest",
                "records": records,
            }
            json_out_path = Path(args.json_out).resolve()
            json_out_path.write_text(json.dumps(payload, indent=2), encoding="utf-8")
            print(f"[obs-debug] wrote JSON dump to {json_out_path}")
    finally:
        env.close()

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
